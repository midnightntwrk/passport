// Regenerate the results table in FINDINGS.md from evidence/*.json.
// Same convention as the sibling experiments: everything between the
// RESULTS markers is machine-written; prose outside them is hand-written.
// A missing FINDINGS.md is created as a marker-bearing skeleton so a first
// run on a clean checkout still produces a readable report.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const EVIDENCE = path.join(ROOT, 'evidence');
const FINDINGS = path.join(ROOT, 'FINDINGS.md');

const BEGIN = '<!-- BEGIN RESULTS (generated by compose-findings.ts) -->';
const END = '<!-- END RESULTS -->';

interface Evidence {
  testId: string;
  name: string;
  verdict: string;
  txHash?: string;
  errorCode?: string;
  note: string;
  ranAt: string;
  stack?: Record<string, string>;
}

const files = fs.existsSync(EVIDENCE)
  ? fs.readdirSync(EVIDENCE).filter((f) => f.endsWith('.json')).sort()
  : [];

const rows: Evidence[] = files
  .map((f) => {
    try {
      return JSON.parse(fs.readFileSync(path.join(EVIDENCE, f), 'utf-8'));
    } catch {
      return null;
    }
  })
  // Only probe evidence carries a verdict; context blobs are skipped.
  .filter((r): r is Evidence => !!r && typeof r.verdict === 'string' && typeof r.testId === 'string')
  // Probe order (P0 … P7), independent of the evidence file names.
  .sort((a, b) => a.testId.localeCompare(b.testId, 'en', { numeric: true }));

const table = [
  '| Probe | Verdict | Tx hash / error | Ran | Note |',
  '|-------|---------|-----------------|-----|------|',
  ...rows.map((r) => {
    const ref = r.txHash ? `\`${r.txHash.slice(0, 16)}…\`` : r.errorCode ? `\`${r.errorCode}\`` : '—';
    const date = r.ranAt?.slice(0, 10).replaceAll('-', '/') ?? '—';
    return `| **${r.testId}** ${r.name} | **${r.verdict}** | ${ref} | ${date} | ${r.note.slice(0, 220)} |`;
  }),
].join('\n');

const stack = rows[rows.length - 1]?.stack;
const stackLine = stack
  ? `Stack: node \`${stack.node}\`, indexer \`${stack.indexer}\`, proof server \`${stack.proofServer}\`, ` +
    `compactc \`${stack.compactc}\`, compact-runtime \`${stack.compactRuntime}\`, midnight-js \`${stack.midnightJs}\`.`
  : '';

if (!fs.existsSync(FINDINGS)) {
  fs.writeFileSync(
    FINDINGS,
    [
      '# Findings — cross-contract calls on the ledger-9 toolchain',
      '',
      '> Skeleton generated by compose-findings.ts; replace this prose with the',
      '> written interpretation. The table between the markers is machine-owned.',
      '',
      BEGIN,
      END,
      '',
    ].join('\n'),
  );
}

const body = fs.readFileSync(FINDINGS, 'utf-8');
const begin = body.indexOf(BEGIN);
const end = body.indexOf(END);
if (begin === -1 || end === -1) {
  console.error('FINDINGS.md is missing the RESULTS markers');
  process.exit(1);
}
fs.writeFileSync(
  FINDINGS,
  body.slice(0, begin + BEGIN.length) +
    '\n\n' + table + '\n' + (stackLine ? `\n${stackLine}\n` : '') + '\n' +
    body.slice(end),
);
console.log(`FINDINGS.md results table regenerated from ${rows.length} evidence file(s).`);
