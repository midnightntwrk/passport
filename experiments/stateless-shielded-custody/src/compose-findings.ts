// Regenerate the results table in FINDINGS.md from evidence/*.json.
// Same convention as dust-sponsorship-feasibility: everything between the
// RESULTS markers is machine-written; prose outside them is hand-written.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const EVIDENCE = path.join(ROOT, 'evidence');
const FINDINGS = path.join(ROOT, 'FINDINGS.md');

const BEGIN = '<!-- BEGIN RESULTS (generated by compose-findings.ts) -->';
const END = '<!-- END RESULTS -->';

interface Evidence {
  testId: string;
  name: string;
  verdict: string;
  txHash?: string;
  errorCode?: string;
  note: string;
  ranAt: string;
}

const files = fs.existsSync(EVIDENCE)
  ? fs.readdirSync(EVIDENCE).filter((f) => f.endsWith('.json')).sort()
  : [];

const rows: Evidence[] = files.map((f) => JSON.parse(fs.readFileSync(path.join(EVIDENCE, f), 'utf-8')));

const table = [
  '| Probe | Verdict | Tx hash / error | Ran | Note |',
  '|-------|---------|-----------------|-----|------|',
  ...rows.map((r) => {
    const ref = r.txHash ? `\`${r.txHash.slice(0, 16)}…\`` : r.errorCode ? `\`${r.errorCode}\`` : '—';
    const date = r.ranAt?.slice(0, 10).replaceAll('-', '/') ?? '—';
    return `| **${r.testId}** ${r.name} | **${r.verdict}** | ${ref} | ${date} | ${r.note.slice(0, 160)} |`;
  }),
].join('\n');

const body = fs.readFileSync(FINDINGS, 'utf-8');
const begin = body.indexOf(BEGIN);
const end = body.indexOf(END);
if (begin === -1 || end === -1) {
  console.error('FINDINGS.md is missing the RESULTS markers');
  process.exit(1);
}
fs.writeFileSync(
  FINDINGS,
  body.slice(0, begin + BEGIN.length) + '\n\n' + table + '\n\n' + body.slice(end),
);
console.log(`FINDINGS.md results table regenerated from ${rows.length} evidence file(s).`);
