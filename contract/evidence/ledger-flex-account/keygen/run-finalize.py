from pathlib import Path
import hashlib,json,os,subprocess,datetime,shutil,time
BASE=Path('/Users/nicolasdiprima/work/iog/midnight/passport/arc-passport/.worktrees/ledger-flex-account/contract')
CACHE=BASE/'contracts/managed/account'
EVIDENCE=BASE/'evidence/ledger-flex-account/keygen'
STAGE=Path('/tmp/ledger-flex-account-finalized')
ADAPTER=Path('/tmp/ledger-flex-account-cache-adapter')
COMPILER=Path('/Users/nicolasdiprima/.compact/versions/0.35.0/aarch64-darwin')
def sha(p):
 h=hashlib.sha256()
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
 return h.hexdigest()
def stamp():return datetime.datetime.now(datetime.timezone.utc).isoformat()
assert not STAGE.exists(),'Refusing existing finalization stage'
report=json.loads((EVIDENCE/'keygen.json').read_text())
verified=json.loads((EVIDENCE/'verification.json').read_text())
context=json.loads((EVIDENCE/'build-context.json').read_text())
assert report['outcome']=='PASS' and len(report['results'])==52
assert sha(EVIDENCE/'keygen.json')==verified['manifest_sha256']
assert sha(COMPILER/'compactc.bin')==context['compiler_binary_sha256']
assert sha(COMPILER/'zkir-v3')==context['zkir_binary_sha256']
for rel,digest in context['compact_sources'].items():assert sha(BASE/rel)==digest,rel
files={}
for r in report['results']:
 name=r['circuit']
 for folder,suffix,key in [('zkir','zkir','source_zkir_sha256'),('keys','prover','prover_sha256'),('keys','verifier','verifier_sha256')]:
  rel=folder+'/'+name+'.'+suffix;p=CACHE/rel;digest=sha(p)
  assert digest==r[key],rel
  files[rel]={'size':p.stat().st_size,'sha256':digest}
 rel='zkir/'+name+'.bzkir';p=CACHE/rel
 assert p.is_file() and p.stat().st_size>0,rel
 files[rel]={'size':p.stat().st_size,'sha256':sha(p)}
receipt={'created_at':stamp(),'cache_root':str(CACHE),'stage':str(STAGE),'keygen_report_sha256':sha(EVIDENCE/'keygen.json'),'compiler_binary_sha256':context['compiler_binary_sha256'],'zkir_binary_sha256':context['zkir_binary_sha256'],'source_hashes':context['compact_sources'],'files':files,'note':'All keys were generated by pinned native zkir-v3; binary IR files were serialized as side effects of those same compile invocations. Compiler finalization reuses this cache only after exact regenerated text-IR and cached-artifact hash checks.'}
(EVIDENCE/'cache-manifest.json').write_text(json.dumps(receipt,indent=2)+'\n')
ADAPTER.mkdir(exist_ok=True)
wrapper=ADAPTER/'zkir-v3'
wrapper.write_text('''#!/usr/bin/python3
from pathlib import Path
import sys,json,hashlib,shutil,datetime
EVIDENCE=Path("/Users/nicolasdiprima/work/iog/midnight/passport/arc-passport/.worktrees/ledger-flex-account/contract/evidence/ledger-flex-account/keygen")
def sha(p):
 h=hashlib.sha256()
 with p.open("rb") as f:
  for b in iter(lambda:f.read(1024*1024),b""):h.update(b)
 return h.hexdigest()
assert len(sys.argv)==4 and sys.argv[1]=="compile-many", "Only compiler compile-many is supported"
r=json.loads((EVIDENCE/"cache-manifest.json").read_text())
cache=Path(r["cache_root"]);stage=Path(r["stage"]).resolve()
ir=Path(sys.argv[2]);keys=Path(sys.argv[3])
assert ir.resolve()==stage/"zkir" and keys.resolve()==stage/"keys", "Unexpected stage paths"
expected={Path(rel).name for rel in r["files"] if rel.startswith("zkir/") and rel.endswith(".zkir")}
assert len(expected)==52 and {p.name for p in ir.iterdir()}==expected, "Regenerated circuit set mismatch"
for name in sorted(expected):
 assert sha(ir/name)==r["files"]["zkir/"+name]["sha256"], "Regenerated IR mismatch: "+name
for rel,entry in r["files"].items():
 p=cache/rel
 assert p.stat().st_size==entry["size"] and sha(p)==entry["sha256"], "Cached artifact mismatch: "+rel
assert not keys.exists() or (keys.is_dir() and not any(keys.iterdir())), "Staging key directory is not empty"
keys.mkdir(exist_ok=True)
for rel,entry in r["files"].items():
 if rel.endswith(".zkir"):continue
 src=cache/rel;dst=stage/rel
 shutil.copyfile(src,dst)
 assert dst.stat().st_size==entry["size"] and sha(dst)==entry["sha256"], "Copied artifact mismatch: "+rel
result={"outcome":"PASS","timestamp":datetime.datetime.now(datetime.timezone.utc).isoformat(),"adapter_sha256":sha(Path(__file__)),"cache_manifest_sha256":sha(EVIDENCE/"cache-manifest.json"),"cache_root":str(cache),"stage":str(stage),"regenerated_text_ir_checked":52,"cached_artifacts_rehashed":208,"artifacts_copied_and_rehashed":156}
(EVIDENCE/"cache-replay.json").write_text(json.dumps(result,indent=2)+"\\n")
print("Verified native-key cache replay: 52 exact IR matches; all 208 artifacts rehashed; copied 156 binary IR/key files",flush=True)
''')
wrapper.chmod(0o755)
(EVIDENCE/'cache-adapter.py').write_bytes(wrapper.read_bytes())
shutil.copyfile('/tmp/ledger-flex-finalize.py',EVIDENCE/'run-finalize.py')
env=os.environ.copy();env['PATH']=str(ADAPTER)+os.pathsep+str(COMPILER)+os.pathsep+env['PATH'];env['RAYON_NUM_THREADS']='2'
command=[str(COMPILER/'compactc.bin'),'--feature-zkir-v3','contracts/account.compact',str(STAGE)]
start=time.monotonic()
print('Starting compiler-native finalization in '+str(STAGE),flush=True)
with (EVIDENCE/'compiler-finalize.log').open('w') as log:
 result=subprocess.run(command,cwd=BASE,env=env,stdout=log,stderr=subprocess.STDOUT)
summary={'exit_code':result.returncode,'elapsed_seconds':round(time.monotonic()-start,3),'finished_at':stamp(),'command':command,'cwd':str(BASE),'task_local_path_prefix':[str(ADAPTER),str(COMPILER)],'rayon_num_threads':2}
(EVIDENCE/'compiler-finalize.json').write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps(summary),flush=True)
raise SystemExit(result.returncode)
